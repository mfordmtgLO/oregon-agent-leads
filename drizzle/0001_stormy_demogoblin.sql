CREATE TABLE `agents` (
	`id` int AUTO_INCREMENT NOT NULL,
	`fullName` varchar(255) NOT NULL,
	`brokerage` varchar(255),
	`cityArea` varchar(255),
	`phone` varchar(64),
	`email` varchar(320),
	`websiteBioUrl` text,
	`zillowUrl` text,
	`headshotUrl` text,
	`buyerSideTransactions` text,
	`salesLast12Months` varchar(255),
	`otherProductionStats` text,
	`realtrendsRank` int,
	`realtrendsTotalSides` double,
	`realtrendsVolume` varchar(64),
	`realtrendsVolumeNum` double,
	`dataSources` text,
	`notes` text,
	`isCustom` boolean NOT NULL DEFAULT false,
	`createdAt` timestamp NOT NULL DEFAULT (now()),
	`updatedAt` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
	CONSTRAINT `agents_id` PRIMARY KEY(`id`)
);
